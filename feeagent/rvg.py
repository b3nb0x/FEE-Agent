def streitwert_streitwert_ok(wert: float) -> bool:
    return 0 < wert <= 5_000_000


def gebuehr(streitwert: float, satz: float) -> dict | None:
    """Gebühr in EUR für Streitwert und Rahmensatz (Tabelle 1 RVG)."""
    if not streitwert_streitwert_ok(streitwert):
        return None
    stufe = next((g for grenze, g in TABELLE if streitwert <= grenze),
                 TABELLE[-1][1])
    betrag = round(stufe * satz, 2)
    return {"stufe": stufe, "satz": satz, "betrag": betrag}
